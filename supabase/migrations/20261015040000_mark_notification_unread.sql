create or replace function private.guard_notification_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if tg_op = 'DELETE' then
    raise exception using errcode = '42501', message = 'Notifications are retained.';
  elsif tg_op = 'INSERT' then
    if pg_catalog.current_setting('app.notification_insert_write', true) is distinct from 'on' then
      raise exception using errcode = '42501', message = 'Notifications are generated by trusted database logic.';
    end if;
    return new;
  end if;

  if pg_catalog.current_setting('app.notification_read_write', true) is distinct from 'on'
    or new.id is distinct from old.id
    or new.recipient_id is distinct from old.recipient_id
    or new.category is distinct from old.category
    or new.title is distinct from old.title
    or new.body is distinct from old.body
    or new.source_type is distinct from old.source_type
    or new.source_id is distinct from old.source_id
    or new.event_id is distinct from old.event_id
    or new.dedupe_key is distinct from old.dedupe_key
    or new.created_at is distinct from old.created_at then
    raise exception using errcode = '42501', message = 'Only notification read status can be updated.';
  end if;
  return new;
end;
$function$;

create or replace function private.mark_notification_unread(p_notification_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor_id uuid := (select auth.uid());
begin
  if v_actor_id is null or not (select private.is_active_club_member()) then
    raise exception using errcode = '42501', message = 'An active member account is required.';
  end if;
  if p_notification_id is null then
    raise exception using errcode = '23514', message = 'Notification identifier is invalid.';
  end if;

  perform pg_catalog.set_config('app.notification_read_write', 'on', true);
  update public.notifications
  set read_at = null
  where id = p_notification_id
    and recipient_id = v_actor_id
    and read_at is not null;
  perform pg_catalog.set_config('app.notification_read_write', 'off', true);
end;
$function$;

create or replace function public.mark_notification_unread(p_notification_id uuid)
returns void
language sql
security invoker
set search_path = ''
as $function$
  select private.mark_notification_unread(p_notification_id);
$function$;

revoke all on function private.mark_notification_unread(uuid) from public, anon, authenticated, service_role;
grant execute on function private.mark_notification_unread(uuid) to authenticated;

revoke all on function public.mark_notification_unread(uuid) from public, anon, authenticated, service_role;
grant execute on function public.mark_notification_unread(uuid) to authenticated;
