-- 2. Single and bulk notification deletion RPCs with audit trail.
create or replace function private.delete_notification(p_notification_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor_id uuid := (select auth.uid());
  v_deleted_category text;
begin
  if v_actor_id is null or not (select private.is_active_club_member()) then
    raise exception using errcode = '42501', message = 'An active member account is required.';
  end if;
  if p_notification_id is null then
    raise exception using errcode = '23514', message = 'Notification identifier is invalid.';
  end if;

  perform pg_catalog.set_config('app.notification_delete_write', 'on', true);
  delete from public.notifications
  where id = p_notification_id
    and recipient_id = v_actor_id
  returning category into v_deleted_category;

  if found then
    insert into public.audit_log (
      actor_id, action, entity_type, entity_id, target_member_id,
      before_data, after_data, reason
    ) values (
      v_actor_id, 'notification.deleted', 'notification',
      p_notification_id, v_actor_id,
      pg_catalog.jsonb_build_object('category', v_deleted_category),
      null,
      'Member deleted an in-app notification.'
    );
  end if;
  perform pg_catalog.set_config('app.notification_delete_write', 'off', true);
end;
$function$;

create or replace function public.delete_notification(p_notification_id uuid)
returns void
language sql
security invoker
set search_path = ''
as $function$
  select private.delete_notification(p_notification_id);
$function$;

create or replace function private.delete_all_notifications()
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor_id uuid := (select auth.uid());
  v_count integer;
begin
  if v_actor_id is null or not (select private.is_active_club_member()) then
    raise exception using errcode = '42501', message = 'An active member account is required.';
  end if;

  perform pg_catalog.set_config('app.notification_delete_write', 'on', true);
  delete from public.notifications
  where recipient_id = v_actor_id;
  get diagnostics v_count = row_count;

  if v_count > 0 then
    insert into public.audit_log (
      actor_id, action, entity_type, entity_id, target_member_id,
      before_data, after_data, reason
    ) values (
      v_actor_id, 'notification.cleared_all', 'notification',
      v_actor_id, v_actor_id,
      null,
      pg_catalog.jsonb_build_object('deleted_count', v_count),
      'Member cleared all in-app notifications.'
    );
  end if;
  perform pg_catalog.set_config('app.notification_delete_write', 'off', true);
  return v_count;
end;
$function$;

