-- 3. Formatting and single-recipient notification helpers (using chr(8358) for Naira U+20A6 and chr(8230) for ellipsis U+2026).
create or replace function private.sanitize_notification_text(
  p_text text,
  p_max_len integer
)
returns text
language plpgsql
immutable
security definer
set search_path = ''
as $function$
declare
  v_cleaned text;
begin
  v_cleaned := pg_catalog.btrim(
    pg_catalog.regexp_replace(
      coalesce(p_text, ''),
      '[[:cntrl:]]+',
      ' ',
      'g'
    )
  );
  if v_cleaned = '' then
    return 'Club notification update.';
  end if;
  if pg_catalog.char_length(v_cleaned) > p_max_len then
    return pg_catalog.btrim(pg_catalog.left(v_cleaned, p_max_len - 1)) || pg_catalog.chr(8230);
  end if;
  return v_cleaned;
end;
$function$;

create or replace function private.format_naira_amount(p_amount bigint)
returns text
language sql
immutable
security definer
set search_path = ''
as $function$
  select case
    when p_amount is null then null
    else pg_catalog.chr(8358) || pg_catalog.btrim(pg_catalog.to_char(p_amount, 'FM999,999,999,999,990'))
  end;
$function$;

create or replace function private.format_role_label(p_role text)
returns text
language sql
immutable
security definer
set search_path = ''
as $function$
  select case pg_catalog.lower(coalesce(p_role, ''))
    when 'admin' then 'Admin'
    when 'backup_admin' then 'Backup Admin'
    when 'executive' then 'Executive'
    when 'member' then 'Member'
    when 'lead' then 'Event Lead'
    when 'assistant' then 'Event Assistant'
    when 'committee' then 'Committee Member'
    else initcap(pg_catalog.replace(coalesce(p_role, 'Member'), '_', ' '))
  end;
$function$;

create or replace function private.notify_single_member(
  p_recipient_id uuid,
  p_category text,
  p_dedupe_key text,
  p_source_type text,
  p_source_id uuid,
  p_event_id uuid,
  p_title text,
  p_body text,
  p_actor_id uuid default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if p_recipient_id is null
     or p_recipient_id = p_actor_id
     or p_dedupe_key is null
     or p_title is null
     or p_body is null then
    return;
  end if;

  perform pg_catalog.set_config('app.notification_insert_write', 'on', true);
  perform pg_catalog.set_config('app.notification_content_write', 'on', true);
  insert into public.notifications (
    recipient_id, category, title, body, source_type, source_id,
    event_id, dedupe_key
  )
  select
    profile.id,
    p_category,
    private.sanitize_notification_text(p_title, 120),
    private.sanitize_notification_text(p_body, 300),
    p_source_type,
    p_source_id,
    p_event_id,
    p_dedupe_key
  from public.member_profiles as profile
  left join public.notification_preferences as preference
    on preference.member_id = profile.id
   and preference.category = p_category
  where profile.id = p_recipient_id
    and profile.status = 'active'
    and coalesce(preference.enabled, true)
  on conflict (recipient_id, dedupe_key) do update
    set title = excluded.title,
        body = excluded.body;
  perform pg_catalog.set_config('app.notification_content_write', 'off', true);
  perform pg_catalog.set_config('app.notification_insert_write', 'off', true);
end;
$function$;

-- 4. Shared audit-to-notification copy builder so live triggers and backfills stay identical.
create or replace function private.build_audit_notification_copy(
  p_audit public.audit_log
)
returns table (
  title text,
  officer_body text,
  self_title text,
  self_body text,
  self_category text,
  self_source_type text,
  resolved_event_id uuid
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_target_username text;
  v_actor_username text;
  v_event_id uuid := coalesce(
    p_audit.event_id,
    case
      when (p_audit.after_data ->> 'event_id') ~ '^[0-9a-fA-F-]{36}$'
        then (p_audit.after_data ->> 'event_id')::uuid
      when (p_audit.before_data ->> 'event_id') ~ '^[0-9a-fA-F-]{36}$'
        then (p_audit.before_data ->> 'event_id')::uuid
      when p_audit.entity_type in ('event', 'event_role_assignment', 'event_budget', 'attendance_session')
        then p_audit.entity_id
      else null
    end
  );
  v_event_title text;
  v_role_label text;
  v_amount_ngn bigint;
  v_months_count integer;
  v_months_label text;
  v_fin_kind text;
  v_fin_desc text;
  v_title text;
  v_body text;
  v_self_title text := null;
  v_self_body text := null;
  v_self_category text := null;
  v_self_source_type text := null;
begin
  if p_audit.target_member_id is not null then
    select '@' || mp.username
    into v_target_username
    from public.member_profiles as mp
    where mp.id = p_audit.target_member_id;
  end if;
  v_target_username := coalesce(v_target_username, 'A member');

  if p_audit.actor_id is not null then
    select '@' || mp.username
    into v_actor_username
    from public.member_profiles as mp
    where mp.id = p_audit.actor_id;
  end if;
  v_actor_username := coalesce(v_actor_username, 'an officer');

  if v_event_id is not null then
    select e.title
    into v_event_title
    from public.events as e
    where e.id = v_event_id;
  end if;
  v_event_title := coalesce(
    v_event_title,
    p_audit.after_data ->> 'title',
    p_audit.before_data ->> 'title',
    'the event'
  );

  -- A. Announcements
  if p_audit.action = 'announcement.created' then
    v_title := 'New announcement: ' || coalesce(p_audit.after_data ->> 'title', 'Club circular');
    v_body := coalesce(p_audit.after_data ->> 'message', 'A new club announcement has been published.');

  -- B. Polls
  elsif p_audit.action = 'poll.created' then
    v_title := 'New poll: ' || coalesce(p_audit.after_data ->> 'question', 'Club vote');
    v_body := 'Cast your vote on "' || private.sanitize_notification_text(coalesce(p_audit.after_data ->> 'question', 'the new poll'), 220) || '" before the poll closes.';

  -- C. Attendance session opened
  elsif p_audit.action = 'attendance.session_opened' then
    v_title := 'Attendance open: ' || v_event_title;
    v_body := 'Check in now for ' || v_event_title || ' while the attendance session is open.';

  -- D. Event lifecycle updates
  elsif p_audit.action in (
    'event_created', 'event_details_updated', 'event_completed',
    'event_cancelled', 'event_reopened', 'event_archived'
  ) then
    case p_audit.action
      when 'event_created' then
        v_title := 'New event: ' || v_event_title;
        v_body := v_event_title || ' has been scheduled' || coalesce(' at ' || (p_audit.after_data ->> 'location'), '') || '.';
      when 'event_details_updated' then
        v_title := 'Event updated: ' || v_event_title;
        v_body := 'Schedule or details for ' || v_event_title || ' were updated.';
      when 'event_completed' then
        v_title := 'Event completed: ' || v_event_title;
        v_body := v_event_title || ' was marked as completed.';
      when 'event_cancelled' then
        v_title := 'Event cancelled: ' || v_event_title;
        v_body := v_event_title || ' was cancelled' || coalesce(': ' || p_audit.reason, '.');
      when 'event_reopened' then
        v_title := 'Event reopened: ' || v_event_title;
        v_body := v_event_title || ' was reopened as scheduled.';
      else
        v_title := 'Event archived: ' || v_event_title;
        v_body := v_event_title || ' was archived by ' || v_actor_username || '.';
    end case;

  -- E. Event role assignments & removals
  elsif p_audit.action in ('event_role_assigned', 'event_role_granted', 'event_role_revoked') then
    v_role_label := private.format_role_label(
      coalesce(p_audit.after_data ->> 'role', p_audit.before_data ->> 'role')
    );
    v_self_category := 'event_activity';
    v_self_source_type := 'event';
    if p_audit.action = 'event_role_revoked' then
      v_title := 'Event role removed: ' || v_role_label;
      v_body := v_target_username || '''s ' || v_role_label || ' role for ' || v_event_title || ' was removed.';
      v_self_title := v_title;
      v_self_body := 'Your ' || v_role_label || ' role for ' || v_event_title || ' was removed.';
    else
      v_title := 'Event role assigned: ' || v_role_label;
      v_body := v_target_username || ' was assigned as ' || v_role_label || ' for ' || v_event_title || '.';
      v_self_title := v_title;
      v_self_body := 'You were assigned as ' || v_role_label || ' for ' || v_event_title || '.';
    end if;

  -- F. Membership status & Club role changes
  elsif p_audit.action in (
    'member_approved', 'member_deactivated', 'member_reactivated',
    'member_rejected', 'member_request_rejected',
    'club_role_granted', 'club_role_revoked'
  ) then
    if p_audit.action = 'member_approved' then
      v_title := 'Member approved';
      v_body := v_target_username || '''s membership request was approved by ' || v_actor_username || '.';
      v_self_title := 'Membership approved';
      v_self_body := 'Your Carpenters Family membership was approved and is now active.';
      v_self_category := 'officer_member';
      v_self_source_type := 'audit';
    elsif p_audit.action = 'member_reactivated' then
      v_title := 'Member reactivated';
      v_body := v_target_username || '''s membership was reactivated by ' || v_actor_username || '.';
      v_self_title := 'Membership reactivated';
      v_self_body := 'Your Carpenters Family membership has been reactivated.';
      v_self_category := 'officer_member';
      v_self_source_type := 'audit';
    elsif p_audit.action = 'member_deactivated' then
      v_title := 'Member deactivated';
      v_body := v_target_username || '''s membership was deactivated by ' || v_actor_username || '.';
    elsif p_audit.action in ('member_rejected', 'member_request_rejected') then
      v_title := 'Membership request declined';
      v_body := v_target_username || '''s membership request was declined by ' || v_actor_username || '.';
    elsif p_audit.action = 'club_role_granted' then
      v_role_label := private.format_role_label(p_audit.after_data ->> 'role');
      v_title := 'Club role updated';
      v_body := v_target_username || '''s role changed to ' || v_role_label || '.';
      v_self_title := 'Club role updated';
      v_self_body := 'Your role changed to ' || v_role_label || '.';
      v_self_category := 'officer_member';
      v_self_source_type := 'audit';
    elsif p_audit.action = 'club_role_revoked' then
      v_role_label := private.format_role_label(
        coalesce(p_audit.before_data ->> 'role', p_audit.after_data ->> 'role')
      );
      v_title := 'Club role updated';
      v_body := v_target_username || '''s role changed to Member (was ' || v_role_label || ').';
      v_self_title := 'Club role updated';
      v_self_body := 'Your role changed to Member (was ' || v_role_label || ').';
      v_self_category := 'officer_member';
      v_self_source_type := 'audit';
    end if;

  -- G. Dues & Financial records
  else
    begin
      v_amount_ngn := coalesce(
        (p_audit.after_data ->> 'amount_ngn')::bigint,
        (p_audit.after_data ->> 'monthly_amount_ngn')::bigint,
        (p_audit.after_data ->> 'total_ngn')::bigint,
        (p_audit.after_data ->> 'price_ngn')::bigint,
        (p_audit.before_data ->> 'amount_ngn')::bigint,
        (p_audit.before_data ->> 'total_ngn')::bigint
      );
    exception when others then
      v_amount_ngn := null;
    end;

    if pg_catalog.jsonb_typeof(p_audit.after_data -> 'covered_months') = 'array' then
      v_months_count := pg_catalog.jsonb_array_length(p_audit.after_data -> 'covered_months');
    elsif pg_catalog.jsonb_typeof(p_audit.after_data -> 'coverage') = 'array' then
      v_months_count := pg_catalog.jsonb_array_length(p_audit.after_data -> 'coverage');
    else
      v_months_count := null;
    end if;

    v_months_label := case
      when v_months_count = 1 then '1 month'
      when v_months_count > 1 then v_months_count::text || ' months'
      else null
    end;

    if p_audit.action = 'dues_payment_request_submitted' then
      v_title := 'Dues payment request';
      v_body := v_target_username || ' submitted a dues request of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'dues')
        || coalesce(' (' || v_months_label || ')', '') || '.';

    elsif p_audit.action = 'dues_payment_request_approved' then
      v_title := 'Dues payment approved';
      v_body := v_target_username || ' paid dues of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'dues')
        || coalesce(' (' || v_months_label || ')', '') || '.';
      v_self_title := 'Dues payment approved';
      v_self_body := 'Your dues payment of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'dues')
        || coalesce(' (' || v_months_label || ')', '') || ' was approved.';
      v_self_category := 'dues_reminder';
      v_self_source_type := 'dues';

    elsif p_audit.action = 'dues_payment_recorded' then
      v_title := 'Dues payment recorded';
      v_body := v_target_username || ' paid dues of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'dues')
        || coalesce(' (' || v_months_label || ')', '') || '.';
      v_self_title := 'Dues payment recorded';
      v_self_body := 'Your dues payment of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'dues')
        || coalesce(' (' || v_months_label || ')', '') || ' was recorded.';
      v_self_category := 'dues_reminder';
      v_self_source_type := 'dues';

    elsif p_audit.action = 'dues_payment_request_rejected' then
      v_title := 'Dues request declined';
      v_body := v_target_username || '''s dues payment request was declined by ' || v_actor_username || '.';
      v_self_title := 'Dues request declined';
      v_self_body := 'Your dues payment request was declined: ' || coalesce(p_audit.reason, 'Please review your payment details.');
      v_self_category := 'dues_reminder';
      v_self_source_type := 'dues';

    elsif p_audit.action = 'dues_payment_corrected' then
      v_title := 'Dues payment updated';
      v_body := v_target_username || '''s dues payment was updated to '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'a revised amount')
        || coalesce(' (' || v_months_label || ')', '') || '.';
      v_self_title := 'Dues payment updated';
      v_self_body := 'Your dues payment record was updated to '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'a revised amount')
        || coalesce(' (' || v_months_label || ')', '') || '.';
      v_self_category := 'dues_reminder';
      v_self_source_type := 'dues';

    elsif p_audit.action = 'dues_month_written_off' then
      v_title := 'Dues month written off';
      v_body := v_target_username || '''s dues for '
        || coalesce(p_audit.after_data ->> 'covered_month', 'a billing month')
        || coalesce(' (' || private.format_naira_amount(v_amount_ngn) || ')', '')
        || ' were written off.';
      v_self_title := 'Dues month waived';
      v_self_body := 'Your dues for '
        || coalesce(p_audit.after_data ->> 'covered_month', 'a billing month')
        || coalesce(' (' || private.format_naira_amount(v_amount_ngn) || ')', '')
        || ' were written off.';
      v_self_category := 'dues_reminder';
      v_self_source_type := 'dues';

    elsif p_audit.action = 'dues_rate_changed' then
      v_title := 'Monthly dues rate updated';
      v_body := 'Monthly dues rate set to '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'a new rate')
        || ' effective ' || coalesce(p_audit.after_data ->> 'effective_month', 'upcoming month') || '.';

    elsif p_audit.action in ('club_finance_recorded', 'club_finance_corrected', 'club_finance_voided') then
      v_fin_kind := case
        when coalesce(p_audit.after_data ->> 'kind', p_audit.before_data ->> 'kind') = 'income' then 'income'
        else 'expense'
      end;
      v_fin_desc := coalesce(
        p_audit.after_data ->> 'description',
        p_audit.after_data ->> 'source_note',
        p_audit.after_data ->> 'category_name',
        p_audit.before_data ->> 'description',
        p_audit.before_data ->> 'source_note'
      );
      v_title := 'Club ' || v_fin_kind || case
        when p_audit.action = 'club_finance_voided' then ' voided'
        when p_audit.action = 'club_finance_corrected' then ' updated'
        else ' recorded'
      end;
      v_body := 'Club ' || v_fin_kind || ' of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'an amount')
        || coalesce(' (' || v_fin_desc || ')', '')
        || case
          when p_audit.action = 'club_finance_voided' then ' was voided.'
          when p_audit.action = 'club_finance_corrected' then ' was updated.'
          else ' was recorded.'
        end;

    elsif p_audit.action in ('event_finance_recorded', 'event_finance_corrected', 'event_finance_voided') then
      v_fin_kind := case
        when coalesce(p_audit.after_data ->> 'kind', p_audit.before_data ->> 'kind') = 'income' then 'income'
        else 'expense'
      end;
      v_fin_desc := coalesce(
        p_audit.after_data ->> 'description',
        p_audit.after_data ->> 'category_name',
        p_audit.before_data ->> 'description'
      );
      v_title := 'Event ' || v_fin_kind || case
        when p_audit.action = 'event_finance_voided' then ' voided'
        when p_audit.action = 'event_finance_corrected' then ' updated'
        else ' recorded'
      end;
      v_body := 'Event ' || v_fin_kind || ' of '
        || coalesce(private.format_naira_amount(v_amount_ngn), 'an amount')
        || coalesce(' (' || v_fin_desc || ')', '')
        || ' for ' || v_event_title
        || case
          when p_audit.action = 'event_finance_voided' then ' was voided.'
          when p_audit.action = 'event_finance_corrected' then ' was updated.'
          else ' was recorded.'
        end;

    elsif p_audit.action = 'event_ticket_sale_recorded' then
      v_title := 'Ticket sale recorded';
      v_body := coalesce((p_audit.after_data ->> 'quantity') || ' ticket(s)', 'Ticket sale')
        || coalesce(' (' || private.format_naira_amount(v_amount_ngn) || ')', '')
        || ' recorded for ' || v_event_title || '.';

    elsif p_audit.action like 'event_ticket_%' then
      v_title := 'Event ticketing updated';
      v_body := 'Ticket tier "' || coalesce(p_audit.after_data ->> 'name', p_audit.before_data ->> 'name', 'tier')
        || '"' || coalesce(' (' || private.format_naira_amount(v_amount_ngn) || ')', '')
        || ' updated for ' || v_event_title || '.';

    elsif p_audit.action in ('event_budget_created', 'event_budget_updated') then
      v_title := case
        when p_audit.action = 'event_budget_created' then 'Event budget created'
        else 'Event budget updated'
      end;
      v_body := 'Budget of ' || coalesce(private.format_naira_amount(v_amount_ngn), 'an amount')
        || ' set for ' || v_event_title || '.';

    elsif p_audit.action in (
      'finance_category_created', 'finance_category_retired',
      'event_finance_category_created', 'event_finance_category_renamed', 'event_finance_category_retired'
    ) then
      v_title := 'Finance category updated';
      v_body := 'Finance category "' || coalesce(p_audit.after_data ->> 'name', p_audit.before_data ->> 'name', 'Category')
        || '" was '
        || case
          when p_audit.action like '%created' then 'created.'
          when p_audit.action like '%renamed' then 'renamed.'
          else 'retired.'
        end;

    else
      v_title := 'Financial record updated';
      v_body := coalesce(p_audit.reason, 'A club or event financial record was updated.');
    end if;
  end if;

  return query select
    private.sanitize_notification_text(v_title, 120),
    private.sanitize_notification_text(v_body, 300),
    case when v_self_title is not null then private.sanitize_notification_text(v_self_title, 120) else null end,
    case when v_self_body is not null then private.sanitize_notification_text(v_self_body, 300) else null end,
    v_self_category,
    v_self_source_type,
    v_event_id;
end;
$function$;

-- 5. Rich audit-log notification trigger function.
create or replace function private.notify_from_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_copy record;
begin
  -- Ignore non-notifiable audit actions early
  if new.action not in (
    'announcement.created',
    'poll.created',
    'attendance.session_opened',
    'event_created', 'event_details_updated', 'event_completed',
    'event_cancelled', 'event_reopened', 'event_archived',
    'event_role_assigned', 'event_role_granted', 'event_role_revoked',
    'member_approved', 'member_deactivated', 'member_reactivated',
    'member_rejected', 'member_request_rejected',
    'club_role_granted', 'club_role_revoked',
    'finance_category_created', 'finance_category_retired'
  )
  and new.action not like 'dues_%'
  and new.action not like 'club_finance_%'
  and new.action not like 'event_finance_%'
  and new.action not like 'event_ticket_%'
  and new.action not like 'event_ledger_%'
  and new.action not like 'event_budget_%' then
    return new;
  end if;

  select * into v_copy
  from private.build_audit_notification_copy(new);

  if new.action = 'announcement.created' then
    perform private.fanout_member_notification(
      'announcement', 'announcement:' || new.entity_id::text,
      'announcement', new.entity_id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  elsif new.action = 'poll.created' then
    perform private.fanout_member_notification(
      'new_poll', 'poll:' || new.entity_id::text,
      'poll', new.entity_id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  elsif new.action = 'attendance.session_opened' then
    perform private.fanout_member_notification(
      'attendance_open', 'attendance-open:' || new.entity_id::text,
      'attendance', new.entity_id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  elsif new.action in (
    'event_created', 'event_details_updated', 'event_completed',
    'event_cancelled', 'event_reopened', 'event_archived'
  ) then
    perform private.fanout_member_notification(
      'event_activity', 'event-activity:' || new.id::text,
      'event', v_copy.resolved_event_id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );
    perform private.fanout_officer_notification(
      'officer_event', 'officer-event:' || new.id::text,
      'audit', new.id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  elsif new.action in ('event_role_assigned', 'event_role_granted', 'event_role_revoked') then
    if v_copy.self_body is not null then
      perform private.notify_single_member(
        new.target_member_id,
        v_copy.self_category,
        'event-role-self:' || new.id::text,
        v_copy.self_source_type,
        v_copy.resolved_event_id,
        v_copy.resolved_event_id,
        v_copy.self_title,
        v_copy.self_body,
        new.actor_id
      );
    end if;
    perform private.fanout_officer_notification(
      'officer_event', 'officer-event:' || new.id::text,
      'audit', new.id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  elsif new.action in (
    'member_approved', 'member_deactivated', 'member_reactivated',
    'member_rejected', 'member_request_rejected',
    'club_role_granted', 'club_role_revoked'
  ) then
    if new.action = 'club_role_granted' then
      perform pg_catalog.set_config('app.notification_delete_write', 'on', true);
      delete from public.notifications as n
      using public.audit_log as al
      where n.source_type = 'audit'
        and n.source_id = al.id
        and al.action = 'club_role_revoked'
        and al.target_member_id = new.target_member_id
        and al.actor_id is not distinct from new.actor_id
        and n.created_at >= pg_catalog.transaction_timestamp();
      perform pg_catalog.set_config('app.notification_delete_write', 'off', true);
    end if;

    if v_copy.self_body is not null then
      perform private.notify_single_member(
        new.target_member_id,
        v_copy.self_category,
        'member-self:' || new.id::text,
        v_copy.self_source_type,
        new.id,
        null,
        v_copy.self_title,
        v_copy.self_body,
        new.actor_id
      );
    end if;

    perform private.fanout_officer_notification(
      'officer_member', 'officer-member:' || new.id::text,
      'audit', new.id, null,
      v_copy.title, v_copy.officer_body, new.actor_id
    );

  else
    if v_copy.self_body is not null then
      perform private.notify_single_member(
        new.target_member_id,
        v_copy.self_category,
        'dues-self:' || new.id::text,
        v_copy.self_source_type,
        new.entity_id,
        null,
        v_copy.self_title,
        v_copy.self_body,
        new.actor_id
      );
    end if;

    perform private.fanout_officer_notification(
      'officer_money', 'officer-money:' || new.id::text,
      'audit', new.id, v_copy.resolved_event_id,
      v_copy.title, v_copy.officer_body, new.actor_id
    );
  end if;

  return new;
end;
$function$;

-- 6. Enrich scheduled poll_closing notifications with the poll question.
create or replace function private.queue_poll_closing_notifications(p_as_of timestamptz)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_poll record;
  v_job_key text;
  v_inserted_key text;
  v_count integer := 0;
begin
  if p_as_of is null then
    raise exception using errcode = '23514', message = 'Notification time is invalid.';
  end if;

  for v_poll in
    select poll.id, poll.event_id, poll.question
    from public.announcement_polls as poll
    where poll.closes_at > p_as_of
      and poll.created_at + ((poll.closes_at - poll.created_at) * 0.75) <= p_as_of
      and not exists (
        select 1
        from private.notification_job_runs as run
        where run.job_key = 'poll-closing:' || poll.id::text
      )
    order by poll.closes_at, poll.id
    limit 250
  loop
    v_job_key := 'poll-closing:' || v_poll.id::text;
    insert into private.notification_job_runs (job_key)
    values (v_job_key)
    on conflict (job_key) do nothing
    returning job_key into v_inserted_key;

    if v_inserted_key is not null then
      perform private.fanout_member_notification(
        'poll_closing',
        v_job_key,
        'poll',
        v_poll.id,
        v_poll.event_id,
        private.sanitize_notification_text('Poll closing soon: ' || v_poll.question, 120),
        private.sanitize_notification_text(
          'Cast your vote on "' || private.sanitize_notification_text(v_poll.question, 210) || '" before the poll closes.',
          300
        ),
        null
      );
      v_count := v_count + 1;
    end if;
  end loop;

  return v_count;
end;
$function$;

revoke all on function private.sanitize_notification_text(text, integer) from public, anon, authenticated, service_role;
revoke all on function private.format_naira_amount(bigint) from public, anon, authenticated, service_role;
revoke all on function private.format_role_label(text) from public, anon, authenticated, service_role;
revoke all on function private.notify_single_member(uuid, text, text, text, uuid, uuid, text, text, uuid) from public, anon, authenticated, service_role;
revoke all on function private.build_audit_notification_copy(public.audit_log) from public, anon, authenticated, service_role;
revoke all on function private.notify_from_audit_log() from public, anon, authenticated, service_role;
revoke all on function private.queue_poll_closing_notifications(timestamptz) from public, anon, authenticated, service_role;

-- 7. Backfill existing notifications in public.notifications from their source records.
do $$
declare
  v_notif record;
  v_audit public.audit_log%rowtype;
  v_copy record;
  v_poll_question text;
  v_ann_title text;
  v_ann_msg text;
  v_event_title text;
begin
  perform pg_catalog.set_config('app.notification_content_write', 'on', true);

  -- Backfill poll notifications (new_poll and poll_closing)
  for v_notif in
    select n.id, n.category, n.source_id
    from public.notifications as n
    where n.source_type = 'poll'
      and n.source_id is not null
  loop
    select p.question into v_poll_question
    from public.announcement_polls as p
    where p.id = v_notif.source_id;

    if v_poll_question is not null then
      update public.notifications
      set title = private.sanitize_notification_text(
            case when v_notif.category = 'poll_closing' then 'Poll closing soon: ' else 'New poll: ' end
            || v_poll_question,
            120
          ),
          body = private.sanitize_notification_text(
            'Cast your vote on "' || private.sanitize_notification_text(v_poll_question, 220) || '" before the poll closes.',
            300
          )
      where id = v_notif.id;
    end if;
  end loop;

  -- Backfill announcement notifications
  for v_notif in
    select n.id, n.source_id
    from public.notifications as n
    where n.source_type = 'announcement'
      and n.source_id is not null
  loop
    select a.title, a.message into v_ann_title, v_ann_msg
    from public.announcements as a
    where a.id = v_notif.source_id;

    if v_ann_title is not null then
      update public.notifications
      set title = private.sanitize_notification_text('New announcement: ' || v_ann_title, 120),
          body = private.sanitize_notification_text(coalesce(v_ann_msg, v_ann_title), 300)
      where id = v_notif.id;
    end if;
  end loop;

  -- Backfill attendance_open notifications
  for v_notif in
    select n.id, coalesce(n.event_id, n.source_id) as evt_id
    from public.notifications as n
    where n.source_type = 'attendance'
      and coalesce(n.event_id, n.source_id) is not null
  loop
    select e.title into v_event_title
    from public.events as e
    where e.id = v_notif.evt_id;

    if v_event_title is not null then
      update public.notifications
      set title = private.sanitize_notification_text('Attendance open: ' || v_event_title, 120),
          body = private.sanitize_notification_text('Check in now for ' || v_event_title || ' while the attendance session is open.', 300)
      where id = v_notif.id;
    end if;
  end loop;

  -- Backfill event_activity notifications
  for v_notif in
    select n.id, coalesce(n.event_id, n.source_id) as evt_id, n.dedupe_key
    from public.notifications as n
    where n.source_type = 'event'
      and coalesce(n.event_id, n.source_id) is not null
  loop
    if v_notif.dedupe_key like 'event-activity:%' then
      select * into v_audit
      from public.audit_log as al
      where 'event-activity:' || al.id::text = v_notif.dedupe_key;

      if found then
        select * into v_copy from private.build_audit_notification_copy(v_audit);
        update public.notifications
        set title = v_copy.title,
            body = v_copy.officer_body
        where id = v_notif.id;
      end if;
    end if;
  end loop;

  -- Backfill audit-sourced notifications
  for v_notif in
    select n.id, n.source_id, n.recipient_id
    from public.notifications as n
    where n.source_type = 'audit'
      and n.source_id is not null
  loop
    select * into v_audit
    from public.audit_log as al
    where al.id = v_notif.source_id;

    if found then
      select * into v_copy
      from private.build_audit_notification_copy(v_audit);

      update public.notifications
      set title = case
            when v_notif.recipient_id = v_audit.target_member_id and v_copy.self_title is not null
              then v_copy.self_title
            else v_copy.title
          end,
          body = case
            when v_notif.recipient_id = v_audit.target_member_id and v_copy.self_body is not null
              then v_copy.self_body
            else v_copy.officer_body
          end,
          event_id = coalesce(event_id, v_copy.resolved_event_id)
      where id = v_notif.id;
    end if;
  end loop;

  perform pg_catalog.set_config('app.notification_content_write', 'off', true);
end
$$;
