create or replace function private.queue_dues_notifications(p_month date)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_month date := pg_catalog.date_trunc('month', p_month)::date;
  v_job_key text;
  v_inserted_key text;
  v_count integer;
begin
  if p_month is null or p_month <> v_month
     or v_month > pg_catalog.date_trunc(
       'month', pg_catalog.clock_timestamp() at time zone 'Africa/Lagos'
     )::date then
    raise exception using errcode = '23514', message = 'Dues reminder period is invalid.';
  end if;
  if not exists (
    select 1 from public.dues_rates as rate where rate.effective_month <= v_month
  ) then
    raise exception using errcode = '23514', message = 'The dues rate is not configured.';
  end if;

  v_job_key := 'dues:' || pg_catalog.to_char(v_month, 'YYYY-MM');
  insert into private.notification_job_runs (job_key)
  values (v_job_key)
  on conflict (job_key) do nothing
  returning job_key into v_inserted_key;
  if v_inserted_key is null then
    return 0;
  end if;

  perform pg_catalog.set_config('app.notification_insert_write', 'on', true);
  insert into public.notifications (
    recipient_id, category, title, body, source_type, dedupe_key
  )
  select profile.id, 'dues_reminder', 'Monthly dues reminder',
    'Your dues reminder is ready. Open your private dues page to review your status.',
    'dues', 'dues:' || pg_catalog.to_char(v_month, 'YYYY-MM')
  from public.member_profiles as profile
  join public.dues_membership_periods as period
    on period.member_id = profile.id
   and period.starts_month <= v_month
   and (period.ends_before_month is null or v_month < period.ends_before_month)
  where profile.status = 'active'
    and not exists (
      select 1 from public.dues_month_dispositions as disposition
      where disposition.member_id = profile.id
        and disposition.covered_month = v_month
        and disposition.is_current
    )
  on conflict (recipient_id, dedupe_key) do nothing;
  get diagnostics v_count = row_count;
  perform pg_catalog.set_config('app.notification_insert_write', 'off', true);
  return v_count;
end;
$function$;

create or replace function private.queue_poll_closing_notifications(p_as_of timestamptz)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_poll record;
  v_count integer := 0;
begin
  if p_as_of is null then
    raise exception using errcode = '23514', message = 'Notification time is invalid.';
  end if;
  for v_poll in
    select poll.id, poll.event_id
    from public.announcement_polls as poll
    where poll.closes_at > p_as_of
      and poll.created_at + ((poll.closes_at - poll.created_at) * 0.75) <= p_as_of
    order by poll.closes_at, poll.id
    limit 250
  loop
    perform private.fanout_member_notification(
      'poll_closing', 'poll-closing:' || v_poll.id::text,
      'poll', v_poll.id, v_poll.event_id,
      'Poll closing soon', 'A club poll is closing soon. Open announcements to review it.', null
    );
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$function$;

create or replace function private.generate_scheduled_notifications()
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_local_now timestamp without time zone :=
    pg_catalog.clock_timestamp() at time zone 'Africa/Lagos';
begin
  if pg_catalog.date_part('day', v_local_now)::integer = 1 then
    perform private.queue_dues_notifications(
      pg_catalog.date_trunc('month', v_local_now)::date
    );
  end if;
  perform private.queue_poll_closing_notifications(pg_catalog.clock_timestamp());
end;
$function$;

